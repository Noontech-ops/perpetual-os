import type { Organization, Outcome, Program, Sector } from './types';

type MarketplaceOrg = Organization & { outcomes: Outcome[]; programs: Program[] };

const mkOrg = (
  id: string, name: string, sector: Sector, mission: string,
  city: string, state: string,
  financials: Organization['financials'],
  outcomes: { title: string; metrics: { label: string; value: number; unit: string; target: number }[] }[],
  leaders?: { name: string; title: string; since: string; bio?: string }[],
): MarketplaceOrg => ({
  id, name, legalName: name, ein: '', mission, vision: '', sector,
  founded: '2000-01-01', website: '',
  address: { street: '', city, state, zip: '' },
  phone: '', email: '',
  leadership: leaders ?? [],
  financials,
  programIds: outcomes.map((_, i) => `${id}-prog-${i}`),
  publicProfile: true,
  slug: id,
  createdAt: '2024-01-01T00:00:00Z',
  updatedAt: '2026-11-01T00:00:00Z',
  outcomes: outcomes.map((o, i) => ({
    id: `${id}-out-${i}`,
    programId: `${id}-prog-${i}`,
    sector,
    reportingPeriod: '2026-Q1-Q4',
    metrics: o.metrics.map(m => ({ ...m, periodStart: '2026-01-01', periodEnd: '2026-12-31' })),
    createdAt: '2024-01-01T00:00:00Z',
  })),
  programs: outcomes.map((o, i) => ({
    id: `${id}-prog-${i}`,
    name: o.title,
    description: `${o.title} — tracking ${o.metrics.map(m => m.label.toLowerCase()).join(', ')}.`,
    sector,
    status: 'active' as const,
    startDate: '2024-01-01',
    annualBudget: Math.round(financials.annualBudget / outcomes.length),
    ytdSpend: Math.round((financials.totalExpenses / outcomes.length) * 0.85),
    staffCount: Math.max(2, Math.round(financials.annualBudget / outcomes.length / 100000)),
    clientsServed: o.metrics[0]?.value ?? 0,
    outcomeIds: [`${id}-out-${i}`],
    grantIds: [],
    createdAt: '2024-01-01T00:00:00Z',
  })),
});

const fin = (budget: number, rev: number, exp: number, net: number, cash: number, runway: number): Organization['financials'] => ({
  fiscalYearEnd: '2026-12-31', annualBudget: budget, totalRevenue: rev,
  totalExpenses: exp, netAssets: net, cashOnHand: cash, monthsOfRunway: runway,
});

